  COUNTRY VARCHAR,
  PRIMARY KEY (FEATURE_DATE, CUSTOMER_ID)
);

-- 1) Set the feature date (snapshot date)
SET AS_OF_DATE = CURRENT_DATE();

-- 2) Insert features for that snapshot into the feature table
INSERT INTO FEATURE_STORE.CUSTOMER_FEATURES
(
  FEATURE_DATE,
  CUSTOMER_ID,
  TX_COUNT_30D,
  TX_SUM_30D,
  TX_AVG_30D,
  TX_COUNT_90D,
  DAYS_SINCE_LAST_TX,
  IS_ACTIVE_30D,
  COUNTRY_TX_COUNT,
  SIGNUP_AGE_DAYS,
  IS_PREMIUM,
  COUNTRY
)
WITH tx_agg AS (
  SELECT
    c.CUSTOMER_ID,
    -- transactions in last 30 days
    COALESCE(SUM(
      CASE WHEN t.TX_TS >= DATEADD(day, -30, $AS_OF_DATE::DATE) THEN 1 ELSE 0 END
    ), 0) AS TX_COUNT_30D,

    COALESCE(SUM(
      CASE WHEN t.TX_TS >= DATEADD(day, -30, $AS_OF_DATE::DATE) THEN t.TX_AMOUNT ELSE 0 END
    ), 0) AS TX_SUM_30D,

    -- transactions in last 90 days
    COALESCE(SUM(
      CASE WHEN t.TX_TS >= DATEADD(day, -90, $AS_OF_DATE::DATE) THEN 1 ELSE 0 END
    ), 0) AS TX_COUNT_90D,

    -- last transaction timestamp for the customer
    MAX(t.TX_TS) AS LAST_TX_TS
  FROM RAW.CUSTOMERS c
  LEFT JOIN RAW.TRANSACTIONS t
    ON c.CUSTOMER_ID = t.CUSTOMER_ID
  GROUP BY c.CUSTOMER_ID
),
country_counts AS (
  SELECT
    COUNTRY,
    COUNT(*) AS COUNTRY_COUNT
  FROM RAW.CUSTOMERS
  GROUP BY COUNTRY
)
SELECT
  $AS_OF_DATE::DATE AS FEATURE_DATE,
  c.CUSTOMER_ID,

  -- counts & sums directly from the aggregated CTE
  COALESCE(a.TX_COUNT_30D, 0) AS TX_COUNT_30D,
  COALESCE(a.TX_SUM_30D, 0) AS TX_SUM_30D,

  -- average amount in last 30 days
  CASE
    WHEN COALESCE(a.TX_COUNT_30D, 0) = 0 THEN 0
    ELSE a.TX_SUM_30D / a.TX_COUNT_30D
  END AS TX_AVG_30D,

  COALESCE(a.TX_COUNT_90D, 0) AS TX_COUNT_90D,

  -- days since last transaction
  CASE
    WHEN a.LAST_TX_TS IS NULL THEN NULL
    ELSE DATEDIFF('day', a.LAST_TX_TS, $AS_OF_DATE::DATE)
  END AS DAYS_SINCE_LAST_TX,

  -- activity flag: any transaction in last 30 days?
  CASE
    WHEN a.LAST_TX_TS IS NOT NULL
         AND a.LAST_TX_TS >= DATEADD(day, -30, $AS_OF_DATE::DATE)
    THEN TRUE
    ELSE FALSE
  END AS IS_ACTIVE_30D,

  COALESCE(cc.COUNTRY_COUNT, 0) AS COUNTRY_TX_COUNT,

  -- days since signup
  DATEDIFF('day', c.SIGNUP_DATE, $AS_OF_DATE::DATE) AS SIGNUP_AGE_DAYS,

  c.IS_PREMIUM,
  c.COUNTRY
FROM RAW.CUSTOMERS c
LEFT JOIN tx_agg a
  ON c.CUSTOMER_ID = a.CUSTOMER_ID
LEFT JOIN country_counts cc
  ON c.COUNTRY = cc.COUNTRY;

