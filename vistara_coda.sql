CREATE OR REPLACE TASK FEATURE_STORE.DAILY_MATERIALIZE
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 0 1 * * * UTC'
AS
BEGIN
  -- delete today's snapshot if it already exists (idempotent)
  DELETE FROM FEATURE_STORE.CUSTOMER_FEATURES
  WHERE FEATURE_DATE = CURRENT_DATE();

  -- insert today's snapshot
  INSERT INTO FEATURE_STORE.CUSTOMER_FEATURES
  (
    FEATURE_DATE,
    CUSTOMER_ID,
    TX_COUNT_30D,
    TX_SUM_30D,
    TX_AVG_30D,
    TX_COUNT_90D,
    DAYS_SINCE_LAST_TX,
    IS_ACTIVE_30D,
    COUNTRY_TX_COUNT,
    SIGNUP_AGE_DAYS,
    IS_PREMIUM,
    COUNTRY
  )
  WITH tx_agg AS (
    SELECT
      c.CUSTOMER_ID,
      COALESCE(SUM(
        CASE WHEN t.TX_TS >= DATEADD(day, -30, CURRENT_DATE()) THEN 1 ELSE 0 END
      ), 0) AS TX_COUNT_30D,

      COALESCE(SUM(
        CASE WHEN t.TX_TS >= DATEADD(day, -30, CURRENT_DATE()) THEN t.TX_AMOUNT ELSE 0 END
      ), 0) AS TX_SUM_30D,

      COALESCE(SUM(
        CASE WHEN t.TX_TS >= DATEADD(day, -90, CURRENT_DATE()) THEN 1 ELSE 0 END
      ), 0) AS TX_COUNT_90D,

      MAX(t.TX_TS) AS LAST_TX_TS
    FROM RAW.CUSTOMERS c
    LEFT JOIN RAW.TRANSACTIONS t
      ON c.CUSTOMER_ID = t.CUSTOMER_ID
    GROUP BY c.CUSTOMER_ID
  ),
  country_counts AS (
    SELECT
      COUNTRY,
      COUNT(*) AS COUNTRY_COUNT
    FROM RAW.CUSTOMERS
    GROUP BY COUNTRY
  )
  SELECT
    CURRENT_DATE() AS FEATURE_DATE,
    c.CUSTOMER_ID,
    a.TX_COUNT_30D,
    a.TX_SUM_30D,
    CASE
      WHEN a.TX_COUNT_30D = 0 THEN 0
      ELSE a.TX_SUM_30D / a.TX_COUNT_30D
    END AS TX_AVG_30D,
    a.TX_COUNT_90D,
    CASE
      WHEN a.LAST_TX_TS IS NULL THEN NULL
      ELSE DATEDIFF('day', a.LAST_TX_TS, CURRENT_DATE())
    END AS DAYS_SINCE_LAST_TX,
    CASE
      WHEN a.LAST_TX_TS >= DATEADD(day, -30, CURRENT_DATE()) THEN TRUE
      ELSE FALSE
    END AS IS_ACTIVE_30D,
    COALESCE(cc.COUNTRY_COUNT, 0) AS COUNTRY_TX_COUNT,
    DATEDIFF('day', c.SIGNUP_DATE, CURRENT_DATE()) AS SIGNUP_AGE_DAYS,
    c.IS_PREMIUM,
    c.COUNTRY
  FROM RAW.CUSTOMERS c
  LEFT JOIN tx_agg a
    ON c.CUSTOMER_ID = a.CUSTOMER_ID
  LEFT JOIN country_counts cc
    ON c.COUNTRY = cc.COUNTRY;
END;

ALTER TASK FEATURE_STORE.DAILY_MATERIALIZE RESUME;
