-- Create outcome table: did customer churn in next 30 days after FEATURE_DATE?
CREATE OR REPLACE TABLE RAW.CUSTOMER_OUTCOMES (
  CUSTOMER_ID VARCHAR,
  OUTCOME_DATE DATE,     -- date the outcome is defined (e.g., FEATURE_DATE)
  IS_CHURN BOOLEAN
);

-- Example insertion for demonstration (derive from transactions)
INSERT INTO RAW.CUSTOMER_OUTCOMES (CUSTOMER_ID, OUTCOME_DATE, IS_CHURN)
SELECT
  cf.CUSTOMER_ID,
  cf.FEATURE_DATE AS OUTCOME_DATE,
  CASE WHEN MAX(t.TX_TS) OVER (PARTITION BY cf.CUSTOMER_ID) <= DATEADD(day, 30, cf.FEATURE_DATE) THEN FALSE
       ELSE FALSE END -- placeholder; for real label define correctly
FROM FEATURE_STORE.CUSTOMER_FEATURES cf
LEFT JOIN RAW.TRANSACTIONS t
  ON cf.CUSTOMER_ID = t.CUSTOMER_ID;

CREATE OR REPLACE TABLE ML.TRAINING_CUSTOMER_DATA AS
SELECT
  f.FEATURE_DATE,
  f.CUSTOMER_ID,
  f.TX_COUNT_30D,
  f.TX_SUM_30D,
  f.TX_AVG_30D,
  f.TX_COUNT_90D,
  f.DAYS_SINCE_LAST_TX,
  f.IS_ACTIVE_30D,
  f.COUNTRY_TX_COUNT,
  f.SIGNUP_AGE_DAYS,
  f.IS_PREMIUM,
  COALESCE(o.IS_CHURN, FALSE) AS IS_CHURN
FROM FEATURE_STORE.CUSTOMER_FEATURES f
LEFT JOIN RAW.CUSTOMER_OUTCOMES o
  ON f.CUSTOMER_ID = o.CUSTOMER_ID AND f.FEATURE_DATE = o.OUTCOME_DATE;

